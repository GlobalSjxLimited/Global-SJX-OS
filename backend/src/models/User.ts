import { Schema, model, Types, InferSchemaType } from 'mongoose';
import bcrypt from 'bcryptjs';
import { ALL_ROLES } from '../config/roles';
import { softDeletePlugin } from '../utils/softDeletePlugin';

const userSchema = new Schema(
  {
    organizationId: { type: Schema.Types.ObjectId, ref: 'Organization', required: true, index: true },
    name: { type: String, required: true, trim: true },
    email: { type: String, required: true, unique: true, lowercase: true, trim: true },
    passwordHash: { type: String, required: true, select: false },
    role: { type: String, enum: ALL_ROLES, required: true, default: 'employee' },
    avatarUrl: { type: String },
    phone: { type: String },

    // Employee-management fields (populated for internal staff roles)
    jobTitle: { type: String },
    department: {
      type: String,
      enum: [
        'Executive',
        'Cybersecurity',
        'Payments',
        'Cloud & Infrastructure',
        'Digital Transformation',
        'Advisory',
        'Sales',
        'HR',
        'Finance',
        'Marketing',
        'Operations',
        'IT & Governance',
        'Risk & Compliance',
        'Academy',
      ],
    },
    managerId: { type: Schema.Types.ObjectId, ref: 'User' },
    /** departments this person heads — tasks "to be reviewed" and escalations for those departments go to them */
    headOfDepartments: [{ type: String }],
    employmentStatus: { type: String, enum: ['active', 'on_leave', 'offboarded'], default: 'active' },
    dateJoined: { type: Date },
    dateOfBirth: { type: Date }, // optional — powers the Hub's "upcoming birthdays" widget when an employee has chosen to share it
    skills: [{ type: Schema.Types.ObjectId, ref: 'Skill' }],

    // External-portal linkage (client contact / vendor contact / academy customer)
    linkedClientId: { type: Schema.Types.ObjectId, ref: 'Client' },
    linkedVendorId: { type: Schema.Types.ObjectId, ref: 'Vendor' },

    lastLoginAt: { type: Date },
    isActive: { type: Boolean, default: true },

    // MFA (TOTP). mfaSecret is only set once mfaEnabled is confirmed;
    // mfaPendingSecret holds a secret generated by /mfa/setup until the user
    // confirms it with a valid code via /mfa/verify — this two-step flow
    // means a half-finished setup never locks anyone out.
    mfaEnabled: { type: Boolean, default: false },
    mfaSecret: { type: String, select: false },
    mfaPendingSecret: { type: String, select: false },

    // Session & lockout security
    tokenVersion: { type: Number, default: 0 }, // bump to revoke all sessions
    failedLoginCount: { type: Number, default: 0 },
    lockUntil: { type: Date },
    passwordChangedAt: { type: Date },
    lastLoginIp: { type: String },
    securityAcknowledgedAt: { type: Date }, // user accepted the information security policy

    // ---- Employee record ----
    employeeNo: { type: String, index: true },
    employmentType: { type: String, enum: ['full_time', 'part_time', 'contract', 'intern', 'consultant'], default: 'full_time' },
    workLocation: { type: String },
    address: { type: String },
    emergencyContact: { name: String, relationship: String, phone: String },
    // Payment details (for expense reimbursement / payroll). The number is AES-256-GCM encrypted and never returned by default.
    bankAccount: {
      bankName: { type: String },
      accountName: { type: String },
      accountNumberEnc: { type: String, select: false },
      accountLast4: { type: String },
    },

    // ---- Credentials & module access ----
    loginEnabled: { type: Boolean, default: true }, // false = employee record only, no system login
    mustChangePassword: { type: Boolean, default: false },
    credentialsIssuedAt: { type: Date },
    credentialsIssuedById: { type: Schema.Types.ObjectId, ref: 'User' },
    moduleGrant: [{ type: String }], // extra modules on top of the role defaults
    moduleDeny: [{ type: String }], // modules removed from the role defaults for this person
    passwordHistory: { type: [String], select: false, default: [] },
    securityPrefs: {
      loginNotifications: { type: Boolean, default: true },
      suspiciousActivityAlerts: { type: Boolean, default: true },
      sessionTimeoutMinutes: { type: Number, default: 60 },
    },
    offboardedAt: { type: Date },
    offboardReason: { type: String },
  },
  { timestamps: true }
);

userSchema.methods.comparePassword = async function comparePassword(candidate: string): Promise<boolean> {
  return bcrypt.compare(candidate, this.passwordHash);
};

userSchema.statics.hashPassword = async function hashPassword(plain: string): Promise<string> {
  const salt = await bcrypt.genSalt(10);
  return bcrypt.hash(plain, salt);
};

export type UserDoc = InferSchemaType<typeof userSchema> & {
  _id: Types.ObjectId;
  comparePassword(candidate: string): Promise<boolean>;
};

userSchema.plugin(softDeletePlugin);
export const User = model('User', userSchema);
