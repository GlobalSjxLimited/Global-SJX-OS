import { Schema, model } from 'mongoose';
import { softDeletePlugin } from '../utils/softDeletePlugin';
import { stampPlugin } from '../utils/stampPlugin';

export const RISK_LEVELS = ['low', 'medium', 'high', 'critical'] as const;

const riskSchema = new Schema(
  {
    organizationId: { type: Schema.Types.ObjectId, ref: 'Organization', required: true, index: true },
    title: { type: String, required: true, trim: true },
    description: { type: String },
    /** risk = might happen, blocker = stopping work now, issue = already happened */
    kind: { type: String, enum: ['risk', 'blocker', 'issue'], default: 'risk' },
    category: { type: String, enum: ['project', 'financial', 'operational', 'security', 'compliance', 'reputational'], default: 'operational' },
    relatedProjectId: { type: Schema.Types.ObjectId, ref: 'Project', index: true },
    relatedMilestoneId: { type: Schema.Types.ObjectId, index: true },
    relatedTaskId: { type: Schema.Types.ObjectId, ref: 'Task', index: true },
    relatedClientId: { type: Schema.Types.ObjectId, ref: 'Client' },
    ownerId: { type: Schema.Types.ObjectId, ref: 'User' },
    raisedById: { type: Schema.Types.ObjectId, ref: 'User' },
    /** how bad it is if it happens (replaces "likelihood") */
    severity: { type: String, enum: RISK_LEVELS, default: 'medium' },
    impact: { type: String, enum: RISK_LEVELS, default: 'medium' },
    /** true = this is currently halting the linked task / milestone */
    blocking: { type: Boolean, default: false },
    mitigationPlan: { type: String },
    status: { type: String, enum: ['open', 'mitigating', 'closed'], default: 'open', index: true },
    startDate: { type: Date },
    endDate: { type: Date },
    identifiedAt: { type: Date, default: Date.now },
    resolvedAt: { type: Date },
    autoGenerated: { type: Boolean, default: false }, // true if created by the automation engine
  },
  { timestamps: true }
);

riskSchema.plugin(softDeletePlugin);
riskSchema.plugin(stampPlugin);
export const Risk = model('Risk', riskSchema);
