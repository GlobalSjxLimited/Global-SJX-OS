import archiver from 'archiver';
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { GENERATORS, GENERATOR_MAP, GenCtx } from './generators';
import { RegisterSnapshot } from '../../models/Isms';
import { Organization } from '../../models/Organization';
import { storage } from '../storage.service';
import { ApiError } from '../../utils/ApiError';

const stamp = () => new Date().toISOString().slice(0, 16).replace(/[-:T]/g, '');

async function ctxFor(orgId: string, by: string): Promise<GenCtx> {
  const org: any = await Organization.findById(orgId).select('name').lean();
  return { orgId, orgName: org?.name || 'Global SJX Limited', by };
}

export async function buildRegister(orgId: string, key: string, by: string) {
  const g = GENERATOR_MAP[key]; if (!g) throw ApiError.notFound('Unknown register');
  return { buffer: await g.build(await ctxFor(orgId, by)), fileName: g.fileName };
}

function zipBuffers(files: Array<{ name: string; data: Buffer }>): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const zip = archiver('zip', { zlib: { level: 9 } }); const chunks: Buffer[] = [];
    zip.on('data', (c: Buffer) => chunks.push(c)); zip.on('end', () => resolve(Buffer.concat(chunks))); zip.on('error', reject);
    for (const f of files) zip.append(f.data, { name: f.name });
    zip.finalize();
  });
}

/** Builds every register into one zip, fingerprints it and keeps it so it can be downloaded again unchanged. */
export async function buildPack(orgId: string, o: { trigger: 'schedule' | 'manual'; byName: string; keys?: string[] }) {
  const ctx = await ctxFor(orgId, o.byName);
  const gens = (o.keys?.length ? o.keys.map((k) => GENERATOR_MAP[k]).filter(Boolean) : GENERATORS);
  const files: Array<{ name: string; data: Buffer }> = []; const counts: Record<string, number> = {};
  for (const g of gens) {
    const data = await g.build(ctx);
    files.push({ name: `${g.group.replace(/[^A-Za-z0-9]+/g, '_')}/${g.fileName}`, data }); counts[g.key] = data.length;
  }
  const manifest = ['GLOBAL SJX OS – ISMS evidence pack', `Organisation: ${ctx.orgName}`, `Generated: ${new Date().toISOString()}`, `Generated by: ${o.byName}`, '', 'Register files and SHA-256:', ...files.map((f) => `${crypto.createHash('sha256').update(f.data).digest('hex')}  ${f.name}`)].join('\n');
  files.push({ name: 'MANIFEST.txt', data: Buffer.from(manifest, 'utf8') });
  const zip = await zipBuffers(files);
  const sha256 = crypto.createHash('sha256').update(zip).digest('hex');
  const fileName = `ISMS_evidence_pack_${stamp()}.zip`;
  const dir = path.join(storage.buildDestination(orgId), 'isms-packs'); fs.mkdirSync(dir, { recursive: true });
  const stored = `${crypto.randomUUID()}.zip`;
  fs.writeFileSync(path.join(dir, stored), zip);
  return RegisterSnapshot.create({ organizationId: orgId, kind: 'pack', label: o.trigger === 'schedule' ? 'Scheduled monthly pack' : 'Manual pack', registers: gens.map((g) => g.key), fileName, storageKey: stored, size: zip.length, sha256, trigger: o.trigger, byName: o.byName, counts });
}

export function snapshotPath(orgId: string, storageKey: string) {
  if (!/^[0-9a-f-]{36}\.zip$/.test(storageKey)) throw ApiError.badRequest('Bad file key');
  return path.join(storage.uploadsRoot, orgId, 'isms-packs', storageKey);
}
