import ExcelJS from 'exceljs';
import { ISMS_VERSION } from '../../config/isms';

export const BRAND = { magenta: 'FFC22FD4', gold: 'FFF0A93B', ink: 'FF1B1B22', soft: 'FFF7EEFA' };

export interface DocMeta { docId: string; title: string; clause?: string; policy?: string; orgName: string; generatedBy: string; classification?: string; note?: string }

export function newWorkbook(by: string): ExcelJS.Workbook {
  const wb = new ExcelJS.Workbook();
  wb.creator = `GLOBAL SJX OS – ${by}`; wb.created = new Date(); wb.title = 'ISMS register';
  return wb;
}

/** Cover sheet in the same shape as the company's registers: document ID, classification, version, confidentiality notice. */
export function frontPage(wb: ExcelJS.Workbook, m: DocMeta) {
  const ws = wb.addWorksheet('Front Page', { views: [{ showGridLines: false }] });
  ws.columns = [{ width: 30 }, { width: 70 }];
  ws.mergeCells('A1:B1');
  const t = ws.getCell('A1'); t.value = m.title; t.font = { size: 18, bold: true, color: { argb: 'FFFFFFFF' } }; t.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND.magenta } }; t.alignment = { vertical: 'middle', indent: 1 };
  ws.getRow(1).height = 36;
  const rows: Array<[string, string]> = [
    ['Document ID', m.docId], ['Organisation', m.orgName], ['Document classification', m.classification || 'Internal'], ['Version', ISMS_VERSION],
    ['ISO/IEC 27001:2022 clause', m.clause || ''], ['Procedure this register evidences', m.policy || ''],
    ['Generated', new Date().toISOString().replace('T', ' ').slice(0, 16) + ' UTC'], ['Generated by', m.generatedBy],
    ['Source', 'GLOBAL SJX OS live data – edit records in the app, not in this file'],
    ['Confidentiality', 'No part of this document may be reproduced, stored or transmitted without the written permission of Global SJX Limited.'],
  ];
  if (m.note) rows.push(['Note', m.note]);
  rows.forEach(([k, v], i) => {
    const r = ws.getRow(3 + i); r.getCell(1).value = k; r.getCell(1).font = { bold: true }; r.getCell(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND.soft } };
    r.getCell(2).value = v; r.getCell(2).alignment = { wrapText: true, vertical: 'top' }; r.getCell(1).alignment = { vertical: 'top' };
  });
}

const cellValue = (v: unknown): ExcelJS.CellValue => {
  if (v === undefined || v === null) return '';
  if (v instanceof Date) return v;
  if (typeof v === 'number' || typeof v === 'boolean') return v;
  if (Array.isArray(v)) return v.join(', ');
  if (typeof v === 'object') return JSON.stringify(v);
  const s = String(v);
  // spreadsheet formula injection guard – never let user text start a formula
  return /^[=+\-@]/.test(s) && !/^[+-]?\d+([.,]\d+)?%?$/.test(s) ? `'${s}` : s.slice(0, 32000);
};

export function table(wb: ExcelJS.Workbook, name: string, headers: string[], rows: unknown[][], opts: { title?: string; widths?: number[]; dateCols?: number[] } = {}) {
  const ws = wb.addWorksheet(name.slice(0, 31), { views: [{ state: 'frozen', ySplit: opts.title ? 3 : 1 }] });
  let hr = 1;
  if (opts.title) {
    ws.mergeCells(1, 1, 1, Math.max(headers.length, 2));
    const c = ws.getCell(1, 1); c.value = opts.title; c.font = { bold: true, size: 13, color: { argb: BRAND.ink } };
    hr = 3;
  }
  const head = ws.getRow(hr);
  headers.forEach((h, i) => {
    const c = head.getCell(i + 1); c.value = h.replace(/\n/g, ' ');
    c.font = { bold: true, color: { argb: 'FFFFFFFF' } }; c.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND.magenta } };
    c.alignment = { wrapText: true, vertical: 'middle' }; c.border = { bottom: { style: 'medium', color: { argb: BRAND.gold } } };
  });
  head.height = 34;
  rows.forEach((r) => {
    const row = ws.addRow(r.map(cellValue));
    row.alignment = { vertical: 'top', wrapText: true };
    (opts.dateCols || []).forEach((i) => { const c = row.getCell(i + 1); if (c.value instanceof Date) c.numFmt = 'dd/mm/yyyy'; });
  });
  headers.forEach((h, i) => { ws.getColumn(i + 1).width = opts.widths?.[i] || Math.min(Math.max(h.length + 4, 14), 42); });
  if (headers.length) ws.autoFilter = { from: { row: hr, column: 1 }, to: { row: hr, column: headers.length } };
  return ws;
}

export async function toBuffer(wb: ExcelJS.Workbook): Promise<Buffer> {
  return Buffer.from(await wb.xlsx.writeBuffer());
}
